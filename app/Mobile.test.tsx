import { expect, open, test } from "nsh/test";

test("create an empty album and choose a media source", async () => {
  const app = await open("./MobileEntry.tsx", { platform: "ios", width: 390, height: 844 });
  await app.press("新建相册");
  await app.type("id:mobile-name", "留白");
  await app.press("返回");
  await app.waitFor("新建相册，加入第一张照片。");
  await app.press("新建相册");
  await app.type("id:mobile-name", "留白");
  await app.press("创建空相册");
  await app.waitFor("从照片图库添加");
  expect(app.shows("从文件添加")).toBe(true);
  await app.press("删除相册");
  await app.press("确认");
  await app.waitFor("新建相册，加入第一张照片。");
});

test("read a local album, rename and navigate the accessible landscape shelf", async () => {
  const seed = await open("./App.tsx", { platform: "macos" });
  await seed.press("id:home-add");
  await seed.type("id:album-name", "日光");
  await seed.press("id:save-album");
  const folder = new URL("./native/tests/fixtures", import.meta.url).href.replace(/^asset:/, "file://");
  await seed.dropFiles("id:album-empty", [folder]);
  await seed.waitFor("id:photo-wall");
  const app = await open("./MobileEntry.tsx", { platform: "ios", width: 844, height: 390 });
  await app.press("label:日光，2 张照片");
  await app.waitFor("id:mobile-photo-1");
  await app.press("重命名");
  await app.clear("id:mobile-name");
  await app.type("id:mobile-name", "湖岸");
  await app.press("保存名称");
  await app.waitFor("湖岸");
  await app.press("id:mobile-photo-1");
  await app.press("编辑旁注");
  await app.type("id:mobile-note-title", "清晨");
  await app.press("保存旁注");
  await app.waitFor("清晨");
  await app.press("返回");
  await app.press("返回");
  await app.waitFor("id:mobile-album-list");
  await app.setViewport(390, 844);
  await app.waitFor("id:mobile-album-stack");
  await app.press("label:打开相册：湖岸");
  await app.waitFor("id:mobile-photo-1");
  await app.press("删除相册");
  await app.press("确认");
  await app.waitFor("新建相册，加入第一张照片。");
});
