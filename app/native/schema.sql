CREATE TABLE IF NOT EXISTS albums(id TEXT PRIMARY KEY NOT NULL, name TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS photos(
  id TEXT PRIMARY KEY NOT NULL, path TEXT UNIQUE NOT NULL, digest TEXT UNIQUE,
  title TEXT NOT NULL DEFAULT '', description TEXT NOT NULL DEFAULT '',
  date TEXT NOT NULL DEFAULT '', location TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS members(
  album TEXT NOT NULL REFERENCES albums(id) ON DELETE CASCADE,
  photo TEXT NOT NULL REFERENCES photos(id) ON DELETE CASCADE, position INTEGER NOT NULL,
  PRIMARY KEY(album,photo), UNIQUE(album,position)
);
CREATE TABLE IF NOT EXISTS covers(
  album TEXT PRIMARY KEY NOT NULL, photo TEXT NOT NULL,
  FOREIGN KEY(album,photo) REFERENCES members(album,photo) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY NOT NULL, value TEXT NOT NULL);
